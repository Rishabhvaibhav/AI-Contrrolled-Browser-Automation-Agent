import os
import base64
import asyncio
import logging
from typing import Dict, Any, List, Optional
from playwright.async_api import Page

from core.browser_engine import BrowserEngine
from core.dom_indexer import DOMIndexer
from core.human_emulator import HumanEmulator
from core.llm_client import LLMClient
from core.config import SCREENSHOTS_DIR

logger = logging.getLogger("ShadowBrowser.BaseAgent")

class BaseBrowserAgent:
    """
    Base autonomous browser agent providing observation, action dispatch,
    humanized movement emulation, and action history tracking.
    """

    def __init__(
        self,
        engine: BrowserEngine,
        llm: Optional[LLMClient] = None,
        max_steps: int = 25,
        capture_screenshots: bool = True,
    ):
        self.engine = engine
        self.llm = llm or LLMClient()
        self.max_steps = max_steps
        self.capture_screenshots = capture_screenshots
        self.history: List[Dict[str, Any]] = []
        self.step_counter = 0

    @property
    def page(self) -> Page:
        return self.engine.page

    async def observe(self) -> Dict[str, Any]:
        """
        Observes current browser state: scans interactive DOM elements,
        takes screenshot, and formats text representation.
        """
        # 1. Scan interactive DOM elements and place badges
        dom_state = await DOMIndexer.get_interactive_state(self.page)
        elements = dom_state.get("interactiveElements", [])
        formatted_elements = DOMIndexer.format_elements_for_llm(elements)

        # 2. Capture screenshot
        screenshot_path = None
        screenshot_b64 = None
        if self.capture_screenshots:
            filename = f"step_{self.step_counter}_{int(asyncio.get_event_loop().time())}.png"
            screenshot_path = str(SCREENSHOTS_DIR / filename)
            raw_bytes = await self.engine.take_screenshot(save_path=screenshot_path)
            screenshot_b64 = base64.b64encode(raw_bytes).decode("utf-8")

        # 3. Clean up badges from DOM so page isn't cluttered
        await DOMIndexer.remove_badges(self.page)

        return {
            "step": self.step_counter,
            "url": dom_state.get("url", self.page.url),
            "title": dom_state.get("title", ""),
            "elements": elements,
            "elements_text": formatted_elements,
            "screenshot_path": screenshot_path,
            "screenshot_b64": screenshot_b64,
        }

    async def execute_action(self, action: Dict[str, Any]) -> str:
        """
        Dispatches an action generated by the LLM or heuristic policy
        with humanized mouse movements and delays.
        """
        act_type = action.get("action", "").lower().strip()
        logger.info(f"Executing action: {action}")

        try:
            if act_type == "navigate":
                url = action.get("url", "")
                await self.engine.navigate(url)
                return f"Navigated to {url}"

            elif act_type == "click":
                element_id = int(action.get("element_id", action.get("index", 0)))
                # Rescan to find element locator
                await DOMIndexer.get_interactive_state(self.page)
                loc = await DOMIndexer.get_element_by_index(self.page, element_id)
                await DOMIndexer.remove_badges(self.page)

                if not loc:
                    return f"Error: Element [{element_id}] not found on page."

                # Get bounding box for human mouse curve
                box = await loc.bounding_box()
                if box:
                    center_x = box["x"] + box["width"] / 2
                    center_y = box["y"] + box["height"] / 2
                    await HumanEmulator.move_mouse(self.page, center_x, center_y)
                    await asyncio.sleep(0.1)

                await loc.click()
                await asyncio.sleep(1.0)
                return f"Clicked element [{element_id}]"

            elif act_type in ("type", "input", "fill"):
                element_id = int(action.get("element_id", action.get("index", 0)))
                text = str(action.get("text", action.get("value", "")))

                await DOMIndexer.get_interactive_state(self.page)
                loc = await DOMIndexer.get_element_by_index(self.page, element_id)
                await DOMIndexer.remove_badges(self.page)

                if not loc:
                    return f"Error: Element [{element_id}] not found on page."

                # Click field first
                await loc.click()
                # Clear existing text if requested or if already has value
                if action.get("clear", False):
                    await loc.fill("")
                
                # Human typing emulation
                await HumanEmulator.human_type(loc, text)

                if action.get("press_enter", False):
                    await self.page.keyboard.press("Enter")
                    await asyncio.sleep(1.0)

                return f"Typed '{text}' into element [{element_id}]"

            elif act_type == "press_key":
                key = action.get("key", "Enter")
                await self.page.keyboard.press(key)
                await asyncio.sleep(0.5)
                return f"Pressed key '{key}'"

            elif act_type == "scroll":
                direction = action.get("direction", "down")
                amount = int(action.get("amount", 400))
                await HumanEmulator.smooth_scroll(self.page, direction=direction, distance=amount)
                return f"Scrolled {direction} by {amount}px"

            elif act_type == "upload_file":
                element_id = int(action.get("element_id", action.get("index", 0)))
                file_path = action.get("file_path", "")

                if not os.path.exists(file_path):
                    return f"Error: File does not exist at '{file_path}'"

                await DOMIndexer.get_interactive_state(self.page)
                loc = await DOMIndexer.get_element_by_index(self.page, element_id)
                await DOMIndexer.remove_badges(self.page)

                if not loc:
                    # Try finding standard input[type=file]
                    file_input = self.page.locator("input[type=file]").first
                    if await file_input.count() > 0:
                        await file_input.set_input_files(file_path)
                        return f"Uploaded file '{file_path}' via generic file input."
                    return f"Error: File upload element [{element_id}] not found."

                await loc.set_input_files(file_path)
                await asyncio.sleep(1.5)
                return f"Uploaded file '{file_path}' into element [{element_id}]"

            elif act_type == "select_option":
                element_id = int(action.get("element_id", action.get("index", 0)))
                val = str(action.get("value", ""))

                await DOMIndexer.get_interactive_state(self.page)
                loc = await DOMIndexer.get_element_by_index(self.page, element_id)
                await DOMIndexer.remove_badges(self.page)

                if not loc:
                    return f"Error: Select element [{element_id}] not found."

                await loc.select_option(label=val)
                return f"Selected option '{val}' on element [{element_id}]"

            elif act_type == "wait":
                seconds = float(action.get("seconds", 2.0))
                await asyncio.sleep(seconds)
                return f"Waited {seconds} seconds."

            elif act_type == "done":
                summary = action.get("summary", action.get("result", "Task completed."))
                return f"TASK_COMPLETED: {summary}"

            else:
                return f"Unknown action type: {act_type}"

        except Exception as e:
            logger.error(f"Error executing action {act_type}: {e}")
            return f"Action failed with error: {str(e)}"
