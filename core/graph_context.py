import os
import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional

logger = logging.getLogger("ShadowBrowser.GraphContext")

BASE_DIR = Path(__file__).resolve().parent.parent
GRAPH_JSON_PATH = BASE_DIR / "graphify-out" / "graph.json"
GRAPH_REPORT_PATH = BASE_DIR / "graphify-out" / "GRAPH_REPORT.md"

class GraphContext:
    """
    Interfaces with the Graphify knowledge graph to provide token-optimized
    architectural and dependency context to LLMs, reducing prompt token overhead
    by up to 9x compared to loading raw source files.
    """

    def __init__(self, graph_path: Path = GRAPH_JSON_PATH):
        self.graph_path = graph_path
        self._graph_data: Optional[Dict[str, Any]] = None
        self._load_graph()

    def _load_graph(self):
        """Loads graph.json if present."""
        if self.graph_path.exists():
            try:
                with open(self.graph_path, "r", encoding="utf-8") as f:
                    self._graph_data = json.load(f)
                logger.info(f"Loaded Graphify knowledge graph: {len(self.nodes)} nodes, {len(self.edges)} edges")
            except Exception as e:
                logger.warning(f"Failed to read graph.json: {e}")
                self._graph_data = None
        else:
            self._graph_data = None

    @property
    def is_available(self) -> bool:
        return self._graph_data is not None

    @property
    def nodes(self) -> List[Dict[str, Any]]:
        if not self._graph_data:
            return []
        return self._graph_data.get("nodes", [])

    @property
    def edges(self) -> List[Dict[str, Any]]:
        if not self._graph_data:
            return []
        return self._graph_data.get("edges", [])

    def search_nodes(self, term: str, max_results: int = 10) -> List[Dict[str, Any]]:
        """Finds nodes whose name, label, or file path matches search term."""
        term_lower = term.lower().strip()
        matched = []
        for n in self.nodes:
            label = str(n.get("label", "")).lower()
            node_id = str(n.get("id", "")).lower()
            file_path = str(n.get("file", "")).lower()
            if term_lower in label or term_lower in node_id or term_lower in file_path:
                matched.append(n)
                if len(matched) >= max_results:
                    break
        return matched

    def get_node_neighbors(self, node_id: str) -> Dict[str, List[str]]:
        """Finds callers and callees for a specific node."""
        incoming = []
        outgoing = []
        for edge in self.edges:
            src = edge.get("source")
            tgt = edge.get("target")
            rel = edge.get("relation", "calls")
            if tgt == node_id:
                incoming.append(f"{src} ({rel})")
            if src == node_id:
                outgoing.append(f"{tgt} ({rel})")
        return {"callers": incoming, "dependencies": outgoing}

    def get_token_optimized_context(self, query: str, max_nodes: int = 12) -> str:
        """
        Builds a compact context block for the LLM prompt. Instead of sending
        thousands of lines of source code, it provides exact node signatures,
        roles, and dependency links.
        """
        if not self.is_available:
            return "(Knowledge graph not built yet. Run 'graphify update .' to generate graph.json)"

        matching_nodes = self.search_nodes(query, max_results=max_nodes)
        if not matching_nodes:
            # Fall back to high-centrality God nodes
            matching_nodes = self.nodes[:max_nodes]

        lines = [
            "### Codebase Knowledge Graph Context (Graphify AST Mapping)",
            f"Query Focus: '{query}' | Matched Structural Entities: {len(matching_nodes)}",
            "",
        ]

        for n in matching_nodes:
            nid = n.get("id", "")
            label = n.get("label", nid)
            ntype = n.get("type", "symbol")
            file_ref = n.get("file", "unknown")
            doc = n.get("doc", "").strip().replace("\n", " ")[:120]
            
            neighbors = self.get_node_neighbors(nid)
            deps = ", ".join(neighbors["dependencies"][:4]) or "none"
            callers = ", ".join(neighbors["callers"][:4]) or "none"

            lines.append(f"- [{ntype.upper()}] `{label}` (in `{file_ref}`)")
            if doc:
                lines.append(f"    Summary: {doc}")
            lines.append(f"    Calls -> {deps}")
            lines.append(f"    Called by <- {callers}")

        return "\n".join(lines)

    @staticmethod
    def get_graph_report_summary() -> str:
        """Reads the high-level GRAPH_REPORT.md generated by graphify."""
        if GRAPH_REPORT_PATH.exists():
            try:
                with open(GRAPH_REPORT_PATH, "r", encoding="utf-8") as f:
                    return f.read()
            except Exception as e:
                return f"Error reading report: {e}"
        return "No GRAPH_REPORT.md found. Run 'graphify update .' to generate."
